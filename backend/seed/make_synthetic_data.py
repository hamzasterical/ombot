"""Drop and recreate all tables, then fill them with the demo dataset (app/seeding.py).

Run from backend/:  uv run python seed/make_synthetic_data.py
Re-run it shortly before a demo: scenario times are relative to now ("last night", "3 days ago").
Also writes seed/DEMO_CUSTOMERS.md, the cheat sheet of which customer backs which complaint.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sqlmodel import Session, SQLModel

from app.db import engine
from app.seeding import build

SHEET = ROOT / "seed" / "DEMO_CUSTOMERS.md"


def write_sheet(demo: list[dict]) -> None:
    def cell(text: str | None) -> str:
        return (text or "").replace("|", "\\|")

    lines = [
        "# Demo customers",
        "",
        "Generated by `seed/make_synthetic_data.py`. Submit a complaint with the customer id shown and the",
        "evidence in the database will back it up. Re-seed shortly before a demo: times are relative to the seed time.",
        "",
        "## Frontend presets",
        "",
        "| Customer | What the database shows |",
        "|---|---|",
    ]
    lines += [f"| `{d['customer_id']}` | {cell(d['hint'])} |" for d in demo if d["complaint"] is None]
    lines += ["", "## Labeled complaints", "", "| Customer | Category | Tier | Complaint | What the database shows |", "|---|---|---|---|---|"]
    lines += [
        f"| `{d['customer_id']}` | {d['category']} | {d['tier']} | {cell(d['complaint'])} | {cell(d['hint'])} |"
        for d in demo
        if d["complaint"] is not None
    ]
    SHEET.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    SQLModel.metadata.drop_all(engine)
    SQLModel.metadata.create_all(engine)
    with Session(engine) as session:
        summary = build(session)
    write_sheet(summary.demo)
    print("Seeded: " + ", ".join(f"{n} {table}" for table, n in summary.counts.items()))
    print(f"Demo sheet: {SHEET}")


if __name__ == "__main__":
    main()
